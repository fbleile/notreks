"""Manifest-backed external datasets.

Synthetic benchmarks are generated by :mod:`notreks.synthetic`.  Real or
semi-synthetic benchmarks such as CausalMan and CausalAssembly must instead
be supplied explicitly.  This module defines the deliberately small boundary
between those datasets and the common preparation/solver pipeline.

The manifest is JSON and all paths are resolved relative to the manifest:

.. code-block:: json

   {
     "dataset_id": "causalman_small",
     "observations": "observations.npy",
     "truth_adjacency": "truth_adjacency.npy",
     "weights": "weights.npy",
     "knowledge_pairs": "knowledge_pairs.json",
     "evaluation_target": "causalman_latent_projection",
     "projection": "projection.json",
     "nodes": ["x0", "x1"]
   }

The optional ``projection`` file is preserved for an evaluator; it is not
silently interpreted as an ordinary DAG/CPDAG.  This is important for
benchmarks with latent variables or bidirected edges.
"""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
from typing import Any

import numpy as np


class ExternalDataError(ValueError):
    """Raised when an external dataset manifest is incomplete or invalid."""


@dataclass(frozen=True)
class ExternalDataset:
    manifest_path: Path
    dataset_id: str
    observations_path: Path
    truth_adjacency_path: Path
    knowledge_pairs_path: Path | None
    weights_path: Path | None
    projection_path: Path | None
    evaluation_target: str
    nodes: tuple[str, ...]
    metadata: dict[str, Any]

    @classmethod
    def from_manifest(cls, path: Path) -> "ExternalDataset":
        path = path.expanduser().resolve()
        if not path.is_file():
            raise ExternalDataError(f"external manifest does not exist: {path}")
        try:
            payload = json.loads(path.read_text())
        except json.JSONDecodeError as error:
            raise ExternalDataError(f"invalid external manifest JSON: {path}") from error
        if not isinstance(payload, dict):
            raise ExternalDataError("external manifest must contain a JSON object")

        def required(name: str) -> str:
            value = payload.get(name)
            if not isinstance(value, str) or not value:
                raise ExternalDataError(f"external manifest requires string field {name!r}")
            return value

        root = path.parent
        observations = root / required("observations")
        truth = root / required("truth_adjacency")
        for candidate in (observations, truth):
            if not candidate.is_file():
                raise ExternalDataError(f"external dataset file does not exist: {candidate}")
        weights_value = payload.get("weights")
        weights = root / weights_value if isinstance(weights_value, str) else None
        if weights is not None and not weights.is_file():
            raise ExternalDataError(f"external weights file does not exist: {weights}")
        knowledge_value = payload.get("knowledge_pairs")
        knowledge = root / knowledge_value if isinstance(knowledge_value, str) else None
        if knowledge is not None and not knowledge.is_file():
            raise ExternalDataError(f"external knowledge-pairs file does not exist: {knowledge}")
        projection_value = payload.get("projection")
        projection = root / projection_value if isinstance(projection_value, str) else None
        if projection is not None and not projection.is_file():
            raise ExternalDataError(f"external projection file does not exist: {projection}")

        nodes_value = payload.get("nodes")
        if (not isinstance(nodes_value, list) or not nodes_value or
                any(not isinstance(node, str) or not node for node in nodes_value)):
            raise ExternalDataError("external manifest field 'nodes' must be a non-empty list of strings")
        target = payload.get("evaluation_target", "synthetic_cpdag")
        if not isinstance(target, str) or not target:
            raise ExternalDataError("evaluation_target must be a non-empty string")
        dataset_id = payload.get("dataset_id", path.stem)
        if not isinstance(dataset_id, str) or not dataset_id:
            raise ExternalDataError("dataset_id must be a non-empty string")
        metadata = dict(payload.get("metadata", {})) if isinstance(payload.get("metadata", {}), dict) else {}
        return cls(path, dataset_id, observations, truth, knowledge, weights, projection, target,
                   tuple(nodes_value), metadata)

    def validate_arrays(self) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Validate dimensions and return observations, truth, and weights."""
        expected_checksums = self.metadata.get("artifact_sha256", {})
        if isinstance(expected_checksums, dict):
            for label, candidate in (("observations", self.observations_path),
                                     ("truth_adjacency", self.truth_adjacency_path),
                                     ("weights", self.weights_path),
                                     ("knowledge_pairs", self.knowledge_pairs_path),
                                     ("projection", self.projection_path)):
                expected = expected_checksums.get(label)
                if expected is None or candidate is None:
                    continue
                digest = hashlib.sha256(candidate.read_bytes()).hexdigest()
                if digest != expected:
                    raise ExternalDataError(f"checksum mismatch for {label}: {candidate}")
        observations = np.load(self.observations_path)
        truth = np.load(self.truth_adjacency_path)
        if observations.ndim != 2:
            raise ExternalDataError(f"observations must be a 2-D array, got {observations.shape}")
        dimension = observations.shape[1]
        if truth.shape != (dimension, dimension):
            raise ExternalDataError(
                f"truth_adjacency must have shape {(dimension, dimension)}, got {truth.shape}")
        if np.any(np.diag(truth)):
            raise ExternalDataError("truth_adjacency must have a zero diagonal")
        if np.any((truth != 0) & (truth != 1)):
            raise ExternalDataError("truth_adjacency must be binary")
        if self.nodes and len(self.nodes) != dimension:
            raise ExternalDataError(f"nodes has length {len(self.nodes)}, expected {dimension}")
        if self.weights_path is None:
            weights = np.ones(dimension, dtype=float)
        else:
            weights = np.asarray(np.load(self.weights_path)).reshape(-1)
            if len(weights) != dimension:
                raise ExternalDataError(f"weights has length {len(weights)}, expected {dimension}")
        if not np.isfinite(observations).all() or not np.isfinite(weights).all():
            raise ExternalDataError("observations and weights must be finite")
        return np.asarray(observations), np.asarray(truth), weights

    def available_pairs(self, dimension: int) -> list[tuple[int, int]]:
        """Load supplied prior pairs; never infer them from the truth graph."""
        if self.knowledge_pairs_path is None:
            raise ExternalDataError(
                "external manifest must provide knowledge_pairs; "
                "prior information is not inferred from the truth adjacency")
        try:
            payload = json.loads(self.knowledge_pairs_path.read_text())
        except json.JSONDecodeError as error:
            raise ExternalDataError(f"invalid knowledge-pairs JSON: {self.knowledge_pairs_path}") from error
        if not isinstance(payload, list):
            raise ExternalDataError("knowledge_pairs must be a JSON list of pairs")
        pairs = []
        for pair in payload:
            if (not isinstance(pair, list) or len(pair) != 2 or
                    not all(isinstance(value, int) for value in pair)):
                raise ExternalDataError("each knowledge pair must be a two-element integer list")
            left, right = sorted(pair)
            if left == right or left < 0 or right >= dimension:
                raise ExternalDataError(f"knowledge pair {(left, right)} is outside dimension {dimension}")
            pairs.append((left, right))
        return sorted(set(pairs))


def main(argv: list[str] | None = None) -> None:
    """Validate a manifest supplied on the command line."""
    import argparse
    parser = argparse.ArgumentParser(prog="notreks-external-check")
    parser.add_argument("manifest", type=Path)
    args = parser.parse_args(argv)
    dataset = ExternalDataset.from_manifest(args.manifest)
    observations, truth, weights = dataset.validate_arrays()
    pairs = dataset.available_pairs(observations.shape[1])
    print(json.dumps({"dataset_id": dataset.dataset_id,
                      "observations": list(observations.shape),
                      "truth_adjacency": list(truth.shape),
                      "weights": list(weights.shape),
                      "nodes": len(dataset.nodes),
                      "knowledge_pairs": len(pairs),
                      "evaluation_target": dataset.evaluation_target}, indent=2))


if __name__ == "__main__":
    main()
